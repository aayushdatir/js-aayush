//Switch case

let month = 10
switch(month){
    case 1:
        console.log("January") 
        break;
    case 2:
        console.log("Febuary") 
        break;
    case 3:
        console.log("March") 
        break;
    case 4:
        console.log("April") 
        break;
    default:
        console.log("Default")
        break;
}